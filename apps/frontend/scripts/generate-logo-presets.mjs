/** Recompress Chromium PNG bytes losslessly with Node's built-in zlib. */
function compactPng(dataUri) {
  const png = Buffer.from(dataUri.split(",")[1], "base64");
  const chunks = [];
  const imageData = [];
  let imageIndex = 0;
  for (let offset = 8; offset < png.length;) {
    const length = png.readUInt32BE(offset);
    const chunk = png.subarray(offset, offset + length + 12);
    if (chunk.toString("ascii", 4, 8) === "IDAT") {
      if (!imageData.length) imageIndex = chunks.length;
      imageData.push(chunk.subarray(8, 8 + length));
    } else chunks.push(chunk);
    offset += length + 12;
  }
  const data = deflateSync(inflateSync(Buffer.concat(imageData)), { level: 9 });
  const compressed = Buffer.alloc(data.length + 12);
  compressed.writeUInt32BE(data.length, 0);
  compressed.write("IDAT", 4, "ascii");
  data.copy(compressed, 8);
  compressed.writeUInt32BE(crc32(compressed.subarray(4, data.length + 8)), data.length + 8);
  chunks.splice(imageIndex, 0, compressed);
  return `data:image/png;base64,${Buffer.concat([png.subarray(0, 8), ...chunks]).toString("base64")}`;
}

const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const presets = await page.evaluate(async (items) => {
    return Promise.all(
      items.map(async ({ svg, ...entry }) => {
        const image = new Image();
        image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
        await image.decode();
        const canvas = document.createElement("canvas");
        canvas.width = canvas.height = 256;
        canvas.getContext("2d").drawImage(image, 0, 0, 256, 256);
        return Object.assign(entry, { dataUri: canvas.toDataURL("image/png") });
      }),
    );
  }, sources);
  const header = `/**
 * Generated by scripts/generate-logo-presets.mjs; do not edit raster data by hand.
 * Source: Remix Icon ${info.version}, @iconify-json/ri 1.2.10, Apache-2.0.
 * Changes: selected glyphs colored and rasterized to transparent 256 x 256 PNGs.
 * Attribution and license: public/licenses/remix-icon.txt.
 */
import type { QrLogoPreset } from "@qr-studio/toolkit/editor";

export const editorLogoPresets = `;
  await mkdir(new URL("../src/", import.meta.url), { recursive: true });
  await writeFile(
    new URL("../src/logo-presets.ts", import.meta.url),
    `${header}${JSON.stringify(
      presets.map((preset) => Object.assign(preset, { dataUri: compactPng(preset.dataUri) })),
      null,
      2,
    )} as const satisfies readonly QrLogoPreset[];\n`,
  );
  process.stdout.write(`Generated ${presets.length} local PNG logo presets.\n`);
} finally {
  await browser.close();
}
